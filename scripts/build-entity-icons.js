/**
 * Builds the ck-entity-icons font from the CNC domain SVG sources and syncs
 * the generated CSS block in assets/css/main.css.
 *
 * Sources:  public/icons/data-model/cnc-domain/*.svg
 * Fonts:    public/fonts/cnc-domain/ck-entity-icons.{woff2,ttf}
 * CSS:      rewrites the block between the `ck-entity-icons:start` and
 *           `ck-entity-icons:end` markers in assets/css/main.css, so icon
 *           codepoints never drift from the class definitions.
 *
 * Metrics are tuned to match PrimeIcons optically: PrimeIcons glyphs fill
 * ~100% of the em box and extend into the descent, while the 24-grid sources
 * keep a 2.25-unit live-area padding (~81% fill). --descent 158 aligns the
 * live-area bottom with PrimeIcons' baseline overshoot, and the generated
 * base class scales glyphs by 1/0.814 ~ 1.23 so both sets render at the same
 * size at the same font-size.
 *
 * Run: `npm run icons:build` after adding or editing source SVGs.
 */
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const SOURCE_DIR = join(ROOT, 'public/icons/data-model/cnc-domain');
const FONT_DIR = join(ROOT, 'public/fonts/cnc-domain');
const CSS_FILE = join(ROOT, 'assets/css/main.css');
const FONT_NAME = 'ck-entity-icons';
const FONT_PUBLIC_BASE = '/fonts/cnc-domain';
const CLASS_BASE = 'ck-entity-icon';
const START_MARKER = '/* ck-entity-icons:start */';
const END_MARKER = '/* ck-entity-icons:end */';

const buildDir = join(tmpdir(), `ck-entity-icons-${process.pid}`);
mkdirSync(buildDir, { recursive: true });
mkdirSync(FONT_DIR, { recursive: true });

try {
    execFileSync('npx', [
        'fantasticon', SOURCE_DIR,
        '-o', buildDir,
        '-n', FONT_NAME,
        '-t', 'woff2', '-t', 'ttf',
        '-g', 'css', '-g', 'json',
        '--normalize', 'true',
        '--font-height', '1000',
        '--descent', '158'
    ], { stdio: 'inherit' });

    const generatedCss = readFileSync(join(buildDir, `${FONT_NAME}.css`), 'utf8');
    const codepoints = JSON.parse(readFileSync(join(buildDir, `${FONT_NAME}.json`), 'utf8'));
    const cacheKey = generatedCss.match(/\?([0-9a-f]{16,})/)?.[1];
    if (!cacheKey) throw new Error('Could not read cache key from generated CSS');

    cpSync(join(buildDir, `${FONT_NAME}.woff2`), join(FONT_DIR, `${FONT_NAME}.woff2`));
    cpSync(join(buildDir, `${FONT_NAME}.ttf`), join(FONT_DIR, `${FONT_NAME}.ttf`));

    const iconClasses = Object.entries(codepoints)
        .sort(([, a], [, b]) => a - b)
        .map(([name, code]) => `.${CLASS_BASE}-${name}::before {\n    content: "\\${code.toString(16)}";\n}`)
        .join('\n\n');

    const block = `${START_MARKER}
/* GENERATED by scripts/build-entity-icons.js — do not edit by hand. */
@font-face {
    font-family: '${FONT_NAME}';
    src: url('${FONT_PUBLIC_BASE}/${FONT_NAME}.woff2?${cacheKey}') format('woff2'),
        url('${FONT_PUBLIC_BASE}/${FONT_NAME}.ttf?${cacheKey}') format('truetype');
    font-weight: normal;
    font-style: normal;
    font-display: block;
}

/* Custom CNC entity icon font (built from public/icons/data-model/cnc-domain).
   Behaves like a PrimeIcon class string in every surface (<i :class>, PrimeVue
   Tree/Menu/Tab icon props) and follows the active color scheme.
   font-size compensates the 24-grid live-area padding so these glyphs match
   PrimeIcons' edge-to-edge em fill at the same nominal size. */
.${CLASS_BASE} {
    font-family: '${FONT_NAME}';
    font-size: 1.23em;
    font-style: normal;
    font-weight: normal;
    font-variant: normal;
    text-transform: none;
    line-height: 1;
    display: inline-block;
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
}

${iconClasses}
${END_MARKER}`;

    const css = readFileSync(CSS_FILE, 'utf8');
    const pattern = new RegExp(`${START_MARKER.replace(/[/*]/g, '\\$&')}[\\s\\S]*?${END_MARKER.replace(/[/*]/g, '\\$&')}`);
    if (!pattern.test(css)) throw new Error(`Marker block not found in ${CSS_FILE}`);
    writeFileSync(CSS_FILE, css.replace(pattern, block));

    console.log(`Built ${Object.keys(codepoints).length} icons -> ${FONT_DIR}`);
} finally {
    rmSync(buildDir, { recursive: true, force: true });
}

import { isDetailScreenTemplate } from '~/utils/action-visibility.js';
import { HOME_SCREEN_ROUTE } from '~/packages/processes/src/screen-contract.js';

import {
  actionToLevel,
  levelAtLeast,
  normalizePermissionGrants
} from '~/shared/access-control';

export function resolveVisibleNavigation(navigation = [], permissions = {}) {
  return (navigation || []).filter(item => {
    const requirement = item.requires || {};
    return hasProcessRequirement({ permissions, requirement });
  });
}

export function resolveVisibleScreens(screens = [], permissions = {}) {
  return composeEffectiveScreens(screens).filter(screen => {
    const requirement = screen.required || screen.requires || {};
    return hasProcessRequirement({ permissions, requirement });
  });
}

// Manifest screen resolution by key (screenKey or id) — the one lookup
// every screen consumer (layout chrome, the screens route, panes,
// popups) reads.
export function screenByKey(screens = [], key = '') {
  if (!key) return null;
  return (Array.isArray(screens) ? screens : []).find(screen => (
    screen?.screenKey === key || screen?.id === key
  )) || null;
}

// The default home screen: what stands in when the compiled manifest
// carries no home — no active definition, one that no longer compiles
// (auth hydration degrades that to "no active process"), or an org without
// navigable screens. Sourceless on purpose: the home workspace renders its
// definition-independent surfaces (chats, calls, profile) from an empty
// contract; the manifest only ever ADDS type sections. Canonical contract:
export function defaultHomeScreen() {
  const screenKey = 'home';
  return {
    id: screenKey,
    screenKey,
    label: 'Home',
    kind: 'home',
    template: 'home',
    placement: 'home',
    route: HOME_SCREEN_ROUTE,
    sourceRoute: HOME_SCREEN_ROUTE,
    sources: [],
    regions: [],
    actions: []
  };
}

// The home screen a route renders when its key resolves to nothing: the
// compiled home when one exists, otherwise the sourceless default.
export function resolveDefaultHomeScreen(screens = []) {
  return composeEffectiveScreens(screens).find(screen => screen.template === 'home')
    || defaultHomeScreen();
}

export function resolveProcessEntryRoute({ screens = [], navigation = [] } = {}) {
  const effectiveScreens = processOperationalScreens(composeEffectiveScreens(screens));
  const home = effectiveScreens.find(screen => screen.template === 'home' && screen.route);
  if (home) return home.route;
  const hub = effectiveScreens.find(screen => screen.route && !isDetailScreenTemplate(screen.template) && (screen.placement || 'hub') === 'hub');
  if (hub) return hub.route;
  const navigable = effectiveScreens.find(screen => screen.route && !isDetailScreenTemplate(screen.template));
  if (navigable) return navigable.route;
  const navItem = (navigation || []).find(item => item?.route?.startsWith('/screens/'));
  return navItem?.route || defaultHomeScreen().route;
}

export function composeEffectiveScreens(screens = []) {
  const byKey = new Map();
  for (const screen of screens || []) {
    const normalized = normalizeEffectiveScreen(screen);
    const existing = byKey.get(normalized.screenKey || normalized.id || normalized.route);
    if (!existing) {
      byKey.set(normalized.screenKey || normalized.id || normalized.route, normalized);
      continue;
    }
    existing.required = mergeRequirements(existing.required, normalized.required);
    existing.requires = mergeRequirements(existing.requires, normalized.requires);
    existing.actions = uniqueValues([...(existing.actions || []), ...(normalized.actions || [])]);
    existing.sourceRoleIds = uniqueValues([...(existing.sourceRoleIds || []), ...(normalized.sourceRoleIds || [])]);
    existing.roleIds = uniqueValues([...(existing.roleIds || []), ...(normalized.roleIds || [])]);
    existing.sources = mergeSources(existing.sources || [], normalized.sources || []);
    existing.regions = mergeRegions(existing.regions || [], normalized.regions || []);
  }
  return [...byKey.values()];
}

export function processOperationalScreens(screens = []) {
  return (screens || []).filter(screen => (
    screen
    && screen.kind !== 'system'
    && typeof screen.route === 'string'
    && (screen.route.startsWith('/screens/') || screen.route === HOME_SCREEN_ROUTE)
  ));
}

function normalizeEffectiveScreen(screen = {}) {
  const key = effectiveScreenKey(screen);
  if (!key || key === screen.screenKey) return { ...screen };
  return {
    ...screen,
    screenKey: key,
    route: generatedScreenRoute(key)
  };
}

function effectiveScreenKey(screen = {}) {
  if (screen.template === 'home') return screen.screenKey || screen.id;
  const typeId = screen.typeId;
  if (!typeId || !isAutoGeneratedScreen(screen)) return screen.screenKey || screen.id || screen.route;
  const suffix = isDetailScreenTemplate(screen.template) ? '_detail' : '';
  const scopeValues = Object.values(screen.scope || {}).filter(value => value !== undefined && value !== null && value !== '');
  return [`auto_${typeId}${suffix}`, ...scopeValues].filter(Boolean).map(String).join(':');
}

function isAutoGeneratedScreen(screen = {}) {
  return String(screen.id || '').startsWith('auto_')
    || String(screen.screenKey || '').startsWith('auto_')
    || String(screen.route || '').startsWith('/screens/auto_');
}

function generatedScreenRoute(screenKey) {
  return `/screens/${encodeURIComponent(String(screenKey || ''))}`;
}

function mergeSources(existing = [], next = []) {
  const byKey = new Map(existing.map(source => [sourceKey(source), { ...source }]));
  for (const source of next) {
    const key = sourceKey(source);
    const current = byKey.get(key);
    if (!current) {
      byKey.set(key, { ...source });
      continue;
    }
    current.required = mergeRequirements(current.required, source.required);
    current.filters = { ...(current.filters || {}), ...(source.filters || {}) };
  }
  return [...byKey.values()];
}

function sourceKey(source = {}) {
  return [
    source.typeId || source.id,
    source.mode || '',
    JSON.stringify(source.filters || {}),
    source.identifier || ''
  ].join(':');
}

function mergeRegions(existing = [], next = []) {
  const byKey = new Map(existing.map(region => [regionKey(region), { ...region, actions: [...(region.actions || [])] }]));
  for (const region of next) {
    const key = regionKey(region);
    const current = byKey.get(key);
    if (!current) {
      byKey.set(key, { ...region, actions: [...(region.actions || [])] });
      continue;
    }
    current.actions = uniqueValues([...(current.actions || []), ...(region.actions || [])]);
  }
  return [...byKey.values()];
}

function regionKey(region = {}) {
  return [region.sourceId || region.id, region.slot || '', region.surface || ''].join(':');
}

function mergeRequirements(left = null, right = null) {
  if (!left) return right || null;
  if (!right) return left || null;
  if (left.feature !== right.feature) return left;
  const rules = [left.rule, right.rule].flatMap(flattenRules).filter(Boolean);
  const scopes = [left.scope, right.scope].filter(Boolean);
  const transitions = [left.transitions, right.transitions].flatMap(item => Array.isArray(item) ? item : [item]).filter(Boolean);
  return {
    feature: left.feature,
    level: 'read',
    ...(rules.length === 1 ? { rule: rules[0] } : {}),
    ...(rules.length > 1 ? { rule: { any: dedupeObjects(rules) } } : {}),
    ...(scopes.length === 1 ? { scope: scopes[0] } : {}),
    ...(transitions.length ? { transitions: dedupeObjects(transitions) } : {})
  };
}

function flattenRules(rule) {
  if (!rule) return [];
  if (Array.isArray(rule.any)) return rule.any.flatMap(flattenRules);
  return [rule];
}

function uniqueValues(items = []) {
  return [...new Set(items.filter(item => item !== undefined && item !== null && item !== ''))];
}

function dedupeObjects(items = []) {
  const seen = new Set();
  const result = [];
  for (const item of items) {
    const key = JSON.stringify(item);
    if (seen.has(key)) continue;
    seen.add(key);
    result.push(item);
  }
  return result;
}

export function hasProcessRequirement({ permissions = {}, requirement = {} } = {}) {
  if (!requirement.feature) return true;
  const requiredLevel = requirement.action
    ? actionToLevel(requirement.action, requirement.level || 'read')
    : requirement.level || 'read';
  return normalizePermissionGrants(permissions[requirement.feature]).some(grant => {
    if (!levelAtLeast(grant.level, requiredLevel)) return false;
    if (requirement.action && grant.actions && grant.actions[requirement.action] !== true) return false;
    if (!transitionRequirementMatchesGrant(requirement, grant)) return false;
    if (requirement.scope && !requirementScopeMatchesGrant(requirement.scope, grant.scope || grant)) return false;
    return true;
  });
}

function firstTransition(requirement = {}) {
  const transition = requirement.transition || requirement.transitions;
  return Array.isArray(transition) ? transition[0] : transition;
}

function transitionRequirementMatchesGrant(requirement = {}, grant = {}) {
  const required = firstTransition(requirement);
  if (!required) return true;
  const allowed = grant.transitions || grant.transition;
  if (!allowed) return true;
  const list = Array.isArray(allowed) ? allowed : [allowed];
  return list.some(item => {
    if (typeof item === 'string') return item === required.to || item === `${required.from}->${required.to}`;
    return (!required.from || !item.from || item.from === required.from) && (!required.to || !item.to || item.to === required.to);
  });
}

function requirementScopeMatchesGrant(requiredScope = {}, grantScope = {}) {
  return Object.entries(requiredScope).every(([key, value]) => {
    if (value === undefined || value === null || value === '') return true;
    const grantValue = grantScope[key];
    const grantValues = grantScope[`${key}s`];
    if (grantValue === undefined && !Array.isArray(grantValues)) return true;
    const allowed = Array.isArray(grantValues) ? grantValues : [grantValue];
    return allowed.map(String).includes(String(value));
  });
}

#!/usr/bin/env python3
"""Generic build123d dispatch: one evaluator over the discovered catalog.

A request is `{"op": <catalog id>, "args": {<param>: <value>}}`. The op
resolves through catalog.json (generated by discover.py from the
installed library), the args coerce per the catalog's param types, and
the real build123d callable executes. Stdin JSON in, stdout JSON out:
`python3 dispatch.py < request.json`.

Shape values on the wire are `{kind: "shape", step: <base64>, bounds,
volume?, area?}` — a STEP serialization plus its measured extents. A
shape-typed param accepts one shape value or a list of them.
"""
import base64
import importlib
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
CATALOG = json.load(open(os.path.join(HERE, "catalog.json"), encoding="utf-8"))
OPS = {op["id"]: op for op in CATALOG["ops"]}


class DispatchError(Exception):
    pass


def require_build123d():
    try:
        import build123d  # noqa: F401
    except ImportError as error:
        raise DispatchError(f"build123d is not installed on this executor: {error}")
    return build123d


def shape_from_value(value):
    """A wire shape value -> a build123d Shape (via its STEP payload)."""
    import build123d

    if not isinstance(value, dict) or value.get("kind") != "shape" or "step" not in value:
        raise DispatchError("a shape-typed input must be a shape value {kind: 'shape', step}")
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "shape.step")
        with open(path, "wb") as handle:
            handle.write(base64.b64decode(value["step"]))
        return build123d.import_step(path)


def coerce(name, kind, value):
    if kind == "shape":
        if isinstance(value, list):
            return [shape_from_value(item) for item in value]
        return shape_from_value(value)
    if kind == "number":
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise DispatchError(f"parameter {name} must be a number")
        return value
    if kind == "boolean":
        if not isinstance(value, bool):
            raise DispatchError(f"parameter {name} must be a boolean")
        return value
    if kind == "string":
        if not isinstance(value, str):
            raise DispatchError(f"parameter {name} must be a string")
        return value
    return value


def resolve_target(op):
    module_name, _, qualname = op["target"].partition(":")
    module = importlib.import_module(module_name)
    obj = module
    for part in qualname.split("."):
        obj = getattr(obj, part)
    return obj


def shape_value(shape):
    import build123d

    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "out.step")
        build123d.export_step(shape, path)
        with open(path, "rb") as handle:
            step = base64.b64encode(handle.read()).decode("ascii")
    box = shape.bounding_box()
    value = {
        "kind": "shape",
        "step": step,
        "bounds": {
            "min": [box.min.X, box.min.Y, box.min.Z],
            "max": [box.max.X, box.max.Y, box.max.Z],
        },
    }
    for measure in ("volume", "area"):
        try:
            value[measure] = getattr(shape, measure)
        except Exception:
            pass
    return value


def serialize(result):
    from build123d.topology import Shape

    if isinstance(result, Shape):
        return shape_value(result)
    if isinstance(result, (list, tuple)):
        return [serialize(item) for item in result]
    if isinstance(result, (bool, int, float, str)) or result is None:
        return result
    raise DispatchError(
        f"op result of type {type(result).__name__} has no wire value"
    )


def dispatch(request):
    """Run one request dict; returns the wire value or raises DispatchError."""
    if not isinstance(request, dict):
        raise DispatchError("request must be a JSON object")
    op = OPS.get(request.get("op"))
    if op is None:
        raise DispatchError(f"unknown op {request.get('op')!r}")
    args = request.get("args") or {}
    if not isinstance(args, dict):
        raise DispatchError("args must be a JSON object")

    declared = {param["name"]: param for param in op["params"]}
    for name in args:
        if name not in declared:
            raise DispatchError(f"op {op['id']} takes no parameter {name!r}")

    kwargs = {}
    for param in op["params"]:
        if param["name"] not in args:
            if param["required"]:
                raise DispatchError(f"parameter {param['name']} is required")
            continue
        kwargs[param["name"]] = coerce(param["name"], param["type"], args[param["name"]])

    require_build123d()
    target = resolve_target(op)
    if op["kind"] == "operator":
        receiver = kwargs.pop("shape")
        result = target(receiver, *kwargs.values())
    else:
        result = target(**kwargs)
    return serialize(result)


def main():
    try:
        request = json.load(sys.stdin)
        json.dump(dispatch(request), sys.stdout)
        sys.stdout.write("\n")
    except DispatchError as error:
        json.dump({"error": str(error)}, sys.stderr)
        sys.stderr.write("\n")
        sys.exit(1)
    except Exception as error:  # engine errors carry the real message
        json.dump({"error": f"{type(error).__name__}: {error}"}, sys.stderr)
        sys.stderr.write("\n")
        sys.exit(1)


if __name__ == "__main__":
    main()

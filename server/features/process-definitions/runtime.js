import {
  resolveEffectiveAccess,
  resolveNavigation,
  resolveScreens,
  resolveWorkflow
} from '~/packages/processes/src/index.js';
import * as repository from './repository.js';
import { resolveOrganizationSystemScreens } from '../organizations/system-screens.js';
import { applyOwnerPermissionsToAuth } from '../users/organization-owner.js';

export async function getActiveProcessForOrganization(organizationId) {
  if (!organizationId) return null;
  const raw = await repository.findActiveByOrganization(organizationId);
  return raw || null;
}

export async function getActiveCompiledProcess(organizationId) {
  const active = await getActiveProcessForOrganization(organizationId);
  return active?.data?.compiled || null;
}

export async function resolveProcessAuth(auth = {}) {
  const organizationId = auth.organizationId || auth.memberships?.[0]?.organizationId;
  const compiled = await getActiveCompiledProcess(organizationId);
  if (!compiled) {
    const ownerAuth = applyOwnerPermissionsToAuth(auth);
    const system = resolveOrganizationSystemScreens(ownerAuth);
    return {
      ...ownerAuth,
      navigation: system.navigation,
      screens: system.screens
    };
  }
  const userId = String(auth.userId || '');
  const effectivePermissions = resolveEffectiveAccess({ compiled, userId });
  const ownerAuth = applyOwnerPermissionsToAuth({ ...auth, effectivePermissions });
  const system = resolveOrganizationSystemScreens(ownerAuth);
  const processScreens = ensureDefaultProcessHome(
    stripStaleGeneratedHome(resolveScreens({ compiled, userId })),
    userId
  );
  const processNavigation = stripStaleGeneratedHomeNavigation(
    resolveNavigation({ compiled, userId }),
    processScreens
  );
  const processNavigationWithHome = ensureProcessHomeNavigation(processNavigation, processScreens);
  return {
    ...ownerAuth,
    process: { active: true, schemaVersion: compiled.schemaVersion },
    fieldPolicies: compiled.fieldPolicies || {},
    navigation: [...system.navigation, ...processNavigationWithHome],
    screens: [...system.screens, ...processScreens],
    roleAssignments: compiled.userAccess?.[userId] || null
  };
}

export async function resolveProcessWorkflow({ organizationId, entityType, fallbackWorkflow = null } = {}) {
  const compiled = await getActiveCompiledProcess(organizationId);
  return resolveWorkflow({ compiled, entityType, fallbackWorkflow });
}

export async function resolveProcessCommandService({ organizationId, commandId } = {}) {
  const compiled = await getActiveCompiledProcess(organizationId);
  if (!compiled) return { processActive: false, gated: false, service: null };

  const commandServices = Object.values(compiled.services || {})
    .filter(service => service?.enabled && service.commandId);
  if (!commandServices.length) return { processActive: true, gated: false, service: null };

  const service = commandServices.find(item => item.commandId === commandId) || null;
  return {
    processActive: true,
    gated: true,
    service
  };
}

function stripStaleGeneratedHome(screens = []) {
  const home = (screens || []).find(screen => screen?.template === 'home');
  if (!home) return screens || [];
  const hasAuthoredOperationalScreen = (screens || []).some(screen => (
    screen
    && screen.template !== 'home'
    && screen.kind !== 'system'
    && !isAutoGeneratedScreen(screen)
  ));
  if (hasAuthoredOperationalScreen) return screens || [];
  return (screens || []).filter(screen => screen !== home);
}

function stripStaleGeneratedHomeNavigation(navigation = [], screens = []) {
  const home = (navigation || []).find(item => item?.screenKey?.startsWith('home_') || item?.route?.startsWith('/screens/home_'));
  if (!home) return navigation || [];
  const homeStillPresent = (screens || []).some(screen => (
    screen?.template === 'home'
    && (screen.screenKey === home.screenKey || screen.route === home.route)
  ));
  if (homeStillPresent) return navigation || [];
  return (navigation || []).filter(item => item !== home);
}

function ensureDefaultProcessHome(screens = [], userId = '') {
  const list = [...(screens || [])];
  if (list.some(screen => screen?.template === 'home')) return list;
  const screenKey = `home_${String(userId || 'user')}`;
  return [{
    id: screenKey,
    screenKey,
    label: 'Home',
    kind: 'home',
    template: 'home',
    placement: 'home',
    route: `/screens/${encodeURIComponent(screenKey)}`,
    sourceRoute: `/screens/${encodeURIComponent(screenKey)}`,
    roleIds: [],
    sources: [],
    regions: [],
    actions: []
  }, ...list];
}

function ensureProcessHomeNavigation(navigation = [], screens = []) {
  const list = [...(navigation || [])];
  const home = (screens || []).find(screen => screen?.template === 'home' && screen?.route);
  if (!home) return list;
  if (list.some(item => item?.screenKey === home.screenKey || item?.route === home.route)) return list;
  return [{
    id: home.screenKey || home.id || 'home',
    screenKey: home.screenKey || home.id || 'home',
    route: home.route,
    label: home.label || 'Home',
    kind: 'home',
    placement: 'home'
  }, ...list];
}

function isAutoGeneratedScreen(screen = {}) {
  return String(screen.id || '').startsWith('auto_')
    || String(screen.screenKey || '').startsWith('auto_')
    || String(screen.route || '').startsWith('/screens/auto_');
}
